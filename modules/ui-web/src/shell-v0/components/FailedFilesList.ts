/**
 * <jf-failed-files-list> — Tempdoc 599 §16/B1; design system §1: "One item's problem → at the item".
 *
 * A folder's failed files, inline under that folder in the Library. Lists the FAILED indexing jobs
 * under the watched root (the folder-scoped `/api/indexing-jobs/failed/by-prefix` endpoint), each with
 * its error and per-row actions. "Try again" dispatches the existing user-audience Operation
 * `core.retry-indexing-job` DIRECTLY via the OperationClient (the failed-jobs Resource itself is
 * operator-only, so we do not surface it as a Resource view here — we reuse the Operation, not the
 * Resource). After a retry the list refetches; the folder row's count drops on its own live tick.
 *
 * An instance answers for one folder at a time. Changing `folderPathHash` drops the old folder's rows
 * BEFORE the next render, and every reply is checked against the folder it was asked for, so a late
 * reply for folder A can never fill folder B (C4).
 */
import { html, css, nothing, type TemplateResult } from 'lit';
import { repeat } from 'lit/directives/repeat.js';
import { JfElement } from '../primitives/JfElement.js';
import './Button.js';
import './RowActions.js';
import { icon } from './Icon.js';
import { FocusKeeper } from '../primitives/focusKeeper.js';
import { resolvePathLazy } from '../hooks/resolvePathLazy.js';
import { authorizedFetch } from '../api/authorizedFetch.js';
import { getOperationClient } from '../operations/OperationClient.js';
import { emitEphemeralToast } from './advisory/ephemeralToast.js';
// Tempdoc 911 (885 UL.9) — the by-prefix wire has a contract now: the generated
// record → JSON Schema → {type, Zod} projection of `FailedIndexingJobsResponse`. `state` (the
// RETRY_EXHAUSTED discriminator below) is a declared, required field rather than a String() cast
// off untyped JSON, so a backend that renames or drops it is reported instead of silently
// rendering every row as a plain parse failure — loudly in dev (the boundary throws), as a
// console `[WireContract]` line plus a drift-telemetry entry in prod, where `toRow` below keeps
// the degrade a degrade.
import { parseWireContract } from '../../api/schemas.js';
import {
  failedIndexingJobsResponseSchema,
  type FailedIndexingJobsResponse,
} from '../../api/generated/schema-types/failed-indexing-jobs-response.js';
// Tempdoc 885 item 21b — the ONE spelling of the exhausted terminal state (see its javadoc). The
// by-prefix listing defaults a blank state to `FAILED`, so an older backend keeps the old
// rendering rather than falling into the exhausted arm.
import {
  JOB_STATE_INDEXED_SOURCE_UNREADABLE,
  JOB_STATE_RETRY_EXHAUSTED,
  JOB_STATE_SOURCE_UNREADABLE,
} from '../state/indexingJobStates.js';
import type { PluginHostApi } from '../plugin-api/plugin-types.js';

const RESOURCE_ID = 'core.failed-indexing-jobs';
const RETRY_OP = 'core.retry-indexing-job';

/** One row of the generated by-prefix wire contract — derived, never re-declared (564 facet 4d). */
type FailedRow = FailedIndexingJobsResponse['jobs'][number];

/**
 * Coerce the three fields this component dereferences unconditionally. In the DEV posture the
 * contract already guarantees them (the parse threw otherwise) and this is a no-op; in PROD the
 * "contract" is only a log line plus a `wireDriftTelemetry` entry, and the row is whatever the
 * drifted backend sent — so the guarantee has to be re-established here or it does not exist.
 */
function toRow(raw: FailedRow): FailedRow {
  const j = (raw ?? {}) as Partial<FailedRow>;
  return {
    ...(j as FailedRow),
    pathHash: String(j.pathHash ?? ''),
    state: String(j.state ?? ''),
    errorMessage: String(j.errorMessage ?? ''),
  };
}

const mounted = new Set<FailedFilesList>();

/** Take the reader to a folder's list: the `N failed` chip and the folder's problem both land here. */
export function revealFailedFiles(folderPathHash: string): void {
  for (const list of mounted) if (list.folderPathHash === folderPathHash) list.reveal();
}

export class FailedFilesList extends JfElement {
  static properties = {
    folderPathHash: { type: String, attribute: 'folder-path-hash' },
    observedCount: { type: Number },
    lastKnown: { type: Boolean },
    collapsed: { type: Boolean, reflect: true },
    apiBase: { attribute: 'api-base', type: String },
    host_: { attribute: false },
    rows: { state: true },
    loading: { state: true },
    error: { state: true },
    resolved: { state: true },
  };

  declare folderPathHash: string;
  declare observedCount: number;
  declare lastKnown: boolean;
  /** The list closes with its folder. */
  declare collapsed: boolean;
  declare apiBase: string;
  declare host_: PluginHostApi | undefined;
  declare rows: FailedRow[];
  declare loading: boolean;
  declare error: string | null;
  /** pathHash → resolved display path (lazy). */
  declare resolved: Record<string, string>;

  private targetFolder: string | null = null;
  private requestSerial = 0;
  private targetSerial = 0;
  private revealOnExpand = false;

  constructor() {
    super();
    // L21 — a row that leaves (retried, cancelled, refreshed away) hands focus to its neighbour, else the list.
    new FocusKeeper(this, () => this.renderRoot.querySelector<HTMLElement>('.list'));
    this.folderPathHash = '';
    this.observedCount = 0;
    this.lastKnown = false;
    this.collapsed = false;
    this.apiBase = '';
    this.rows = [];
    this.loading = false;
    this.error = null;
    this.resolved = {};
  }

  override connectedCallback(): void {
    super.connectedCallback();
    mounted.add(this);
    this.requestUpdate('folderPathHash');
  }

  override disconnectedCallback(): void {
    super.disconnectedCallback();
    mounted.delete(this);
    this.requestSerial++;
    this.targetFolder = null;
    this.targetSerial++;
  }

  reveal(): void {
    if (this.collapsed) {
      // A closed folder opens first; the list is revealed once it is on show.
      this.revealOnExpand = true;
      this.dispatchEvent(new CustomEvent('failed-files-expand'));
      return;
    }
    const list = this.renderRoot.querySelector<HTMLElement>('.list');
    list?.scrollIntoView?.({ block: 'nearest' });
    list?.focus();
  }

  /** Before render, so no frame ever shows one folder's rows under another. */
  override willUpdate(changed: Map<string, unknown>): void {
    if (!changed.has('folderPathHash') || this.targetFolder === this.folderPathHash) return;
    this.targetFolder = this.folderPathHash;
    this.rows = [];
    this.resolved = {};
    this.error = null;
    this.loading = false;
    this.requestSerial++;
    this.targetSerial++;
  }

  override updated(changed: Map<string, unknown>): void {
    if (changed.has('collapsed') && !this.collapsed && this.revealOnExpand) {
      this.revealOnExpand = false;
      this.reveal();
    }
    if (changed.has('folderPathHash') || changed.has('observedCount') && !this.lastKnown) void this.refresh();
  }

  private async refresh(): Promise<void> {
    const folder = this.targetFolder;
    if (!folder) return;
    const serial = ++this.requestSerial;
    const current = () => this.isConnected && serial === this.requestSerial && folder === this.targetFolder;
    this.loading = true;
    this.error = null;
    try {
      const res = await this.doFetch(
        `/api/indexing-jobs/failed/by-prefix?pathHash=${encodeURIComponent(folder)}`,
      );
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const parsed = parseWireContract(
        failedIndexingJobsResponseSchema,
        await res.json(),
        'GET /api/indexing-jobs/failed/by-prefix',
      );
      if (!current()) return;
      // PROD-POSTURE DEFENCE. `parseWireContract` throws in dev but RETURNS THE RAW BODY in prod
      // (api/schemas.ts) — its own doc says it degrades "so the downstream mapper is defensive".
      // That mapper is this line: without it, a drifted row reaches render, and `r.state.toUpperCase()`
      // throws a TypeError inside Lit's `performUpdate` — OUTSIDE this try/catch, so `this.error`
      // would never be set and the list would freeze rather than degrade. Normalizing at the ONE
      // parse site (not at each render site) also covers `retryAll` and `onRowActionSuccess`, which
      // key on `pathHash`. Mirrors api/domains/indexing.ts's defensive `(parsed.jobs ?? [])`.
      const rows = (Array.isArray(parsed?.jobs) ? parsed.jobs : []).map(toRow);
      if (rows.length > 0 || !this.rows.length) {
        this.rows = rows;
      }
      // Lazy-resolve hashes → display paths (best-effort; deleted files resolve to null → show hash).
      for (const r of this.rows) {
        if (r.pathHash && !this.resolved[r.pathHash]) {
          void resolvePathLazy(RESOURCE_ID, r.pathHash, { apiBase: this.apiBase }).then((path) => {
            if (path && current()) this.resolved = { ...this.resolved, [r.pathHash]: path };
          });
        }
      }
    } catch (err) {
      if (!current()) return;
      this.error = err instanceof Error ? err.message : String(err);
    } finally {
      if (current()) this.loading = false;
    }
  }

  private doFetch(path: string): Promise<Response> {
    if (this.host_?.data?.fetch) return this.host_.data.fetch(path);
    return authorizedFetch((this.apiBase || '') + path);
  }

  /** "Try again": invoke the existing retry Operation for each listed file, then read the list again. */
  private async retryAll(): Promise<void> {
    const folder = this.targetFolder;
    const serial = this.targetSerial;
    const current = () => this.isConnected && serial === this.targetSerial && folder === this.targetFolder;
    const client = getOperationClient(this.apiBase || '');
    for (const r of [...this.rows]) {
      if (!current()) return;
      try {
        await client.invoke(RETRY_OP, { args: { pathHash: r.pathHash } });
      } catch (err) {
        if (!current()) return;
        // Leave the failed row and its original error visible, and report the retry failure.
        const reason = err instanceof Error ? err.message : String(err ?? '');
        emitEphemeralToast({
          message: `Could not retry failed file.${reason ? ` ${reason}` : ''}`,
          severity: 'error',
        });
      }
    }
    if (current()) await this.refresh();
  }

  static styles = css`
    :host {
      display: block;
      margin: .5rem 0 0 1.7rem;
      --justsearch-shell-form-control-spacing: 0;
    }
    :host([collapsed]) { display: none; }
    .list { max-block-size: var(--frame-failed-list-max); overflow-y: auto; }
    .list:focus { outline: none; }
    .list:focus-visible { outline: var(--frame-focus-width) solid var(--accent-tint); outline-offset: var(--frame-focus-width); }
    /**
     * Tempdoc 914 D2 — the row STACKS; it is not a two-column flex row.
     *
     * A list may be as narrow as a 26rem window: jf-row-actions renders one full-label button per declared
     * item-operation ("Retry indexing job", "Cancel indexing job"). Those buttons do not shrink, so
     * side-by-side they took 339px of the 373px row and squeezed .row-info to 22px — one
     * character per line, an 822px-tall row for a single path. The path IS the row's identity, so
     * it takes the full width and the actions sit under it.
     */
    .row {
      display: flex;
      flex-direction: column;
      align-items: flex-start;
      gap: 0.4rem;
      padding: .4rem 0;
    }
    .row-info {
      inline-size: 100%;
      min-inline-size: 0;
    }
    /* ActionButton's :host carries a form-control bottom margin sized for stacked form fields; in a
       list row that is dead space under the buttons. Withdrawn through its own token, not by
       overriding the component's rule. Only the text size matches the compact Try again beside it. */
    .row jf-row-actions {
      --justsearch-shell-form-control-spacing: 0;
      font-size: var(--font-size-sm);
      max-inline-size: 100%;
    }
    .row-path {
      font-size: var(--font-size-sm);
      color: var(--text-primary);
      overflow-wrap: anywhere;
    }
    .row-error {
      margin-top: 0.15rem;
      font-size: var(--font-size-xs);
      color: var(--text-secondary);
      overflow-wrap: anywhere;
    }
    /* Tempdoc 941 F2 — the scan that produced this failure. Secondary tone: it is provenance for
       correlating a row with a scan in Activity, not part of the failure's explanation. */
    .row-scan {
      margin-top: 0.15rem;
      font-size: var(--font-size-xs);
      color: var(--text-secondary);
      overflow-wrap: anywhere;
    }
    /* 885 item 21b — "we never managed to read it" is a WAITING outcome, not a verdict on the file,
       so it carries the secondary tone rather than the danger tone the parse-failure line uses. */
    .row-gaveup,
    .row-unreadable {
      margin-top: 0.15rem;
      font-size: var(--font-size-xs);
      color: var(--text-secondary);
      overflow-wrap: anywhere;
    }
    .empty,
    .loading {
      padding: .5rem 0;
      text-align: start;
      color: var(--text-secondary);
      font-size: var(--font-size-sm);
    }
  `;

  override render(): TemplateResult {
    return html`<div class="list" tabindex="-1" role="group" aria-label="Files needing review">
      ${this.lastKnown ? html`<p>Last-known failures; retries are in progress.</p>` : nothing}
      ${this.renderBody()}
      ${this.rows.length ? html`<jf-button variant="ghost" label="Try again"
        .onActivate=${() => { void this.retryAll(); /* no promise back: jf-control would hold Try again busy until the batch settles */ }}>${icon({ name: 'refresh-cw', size: 14 })} Try again</jf-button>` : nothing}
    </div>`;
  }

  private renderBody(): TemplateResult {
    // L21 — a refresh keeps the listed rows: an open band and its opener
    // belong to their file, and stay while that file is still listed. A file that leaves takes its band.
    if (this.loading && !this.rows.length) return html`<div class="loading">Loading…</div>`;
    if (this.error && !this.rows.length) return html`<div class="empty">Couldn't load failed files: ${this.error}</div>`;
    if (this.rows.length === 0)
      return html`<div class="empty">No failed files in this folder.</div>`;
    return html`${this.error ? html`<div class="empty" role="status">Couldn't refresh failed files: ${this.error}. Showing the last known list.</div>` : nothing}
      ${repeat(this.rows, row => row.pathHash, row => this.renderRow(row))}`;
  }

  private renderRow(r: FailedRow): TemplateResult {
    const display = this.resolved[r.pathHash] ?? `[${r.pathHash.slice(0, 12)}…]`;
    // Tempdoc 885 item 21b — an exhausted job is NOT a bad file, and the two must not read alike.
    // `errorMessage` on such a row is whichever transient error happened last (an I/O error, a
    // parser timeout), which on its own reads as a verdict about the file; the header says what
    // actually happened and what makes the queue try again, so the error stays as detail rather
    // than as the explanation.
    const exhausted = r.state.toUpperCase() === JOB_STATE_RETRY_EXHAUSTED;
    // #758 — a file that exists but cannot be read is retried without end and its
    // indexed content is kept; it must not read like a broken or a missing file.
    const indexedUnreadable = r.state.toUpperCase() === JOB_STATE_INDEXED_SOURCE_UNREADABLE;
    const unreadable = indexedUnreadable || r.state.toUpperCase() === JOB_STATE_SOURCE_UNREADABLE;
    // Tempdoc 941 F2 — the by-prefix wire has carried `scanId` since 911 but nothing
    // rendered it, so a failed row could not be tied back to the scan that produced it. `""` is the
    // contract's "no owning scan" (single-file ingest / watcher / pre-scan row), NOT an unknown —
    // so that case renders no line at all rather than an empty or invented one. `toRow` does not
    // normalize `scanId` (it coerces only the three fields dereferenced unconditionally), so the
    // prod-posture degrade can still deliver a non-string here.
    const scanId = typeof r.scanId === 'string' ? r.scanId : '';
    const scanShort = scanId.length > 8 ? `${scanId.slice(0, 8)}…` : scanId;
    // Per-row retry/cancel reuse the shared <jf-row-actions> (tempdoc 599 §16.1 Move 1 + §17.2): it
    // reads the failed-jobs Resource's itemOperations and dispatches the user-invocable Operation with
    // {pathHash: rowKey} — no hand-rolled button or direct OperationClient call.
    return html`
      <div class="row" data-focus-row=${r.pathHash} data-state=${r.state || 'FAILED'}>
        <div class="row-info">
          <div class="row-path" title=${display}>${display}</div>
          ${exhausted
            ? html`<div class="row-gaveup" data-testid="failed-job-exhausted">
                Gave up after 7 days of retries — rescan the folder, or edit the file, to try again.
              </div>`
            : nothing}
          ${unreadable
            ? html`<div class="row-unreadable" data-testid="failed-job-source-unreadable">
                ${indexedUnreadable
                  ? 'Indexed, source unreadable — the file is locked or access is denied. Its'
                    + ' indexed content stays searchable; retrying automatically.'
                  : 'Source unreadable — the file is locked or access is denied. Retrying'
                    + ' automatically.'}
              </div>`
            : nothing}
          ${r.errorMessage ? html`<div class="row-error">${r.errorMessage}</div>` : nothing}
          ${scanId
            ? html`<div class="row-scan" data-testid="failed-job-scan" title=${scanId}>
                Scan ${scanShort}
              </div>`
            : nothing}
        </div>
        <jf-row-actions
          resource-id=${RESOURCE_ID}
          row-key=${r.pathHash}
          api-base=${this.apiBase}
        ></jf-row-actions>
      </div>
    `;
  }
}

if (typeof customElements !== 'undefined' && !customElements.get('jf-failed-files-list')) {
  customElements.define('jf-failed-files-list', FailedFilesList);
}
