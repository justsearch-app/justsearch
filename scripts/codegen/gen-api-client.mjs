#!/usr/bin/env node
/**
 * Tempdoc 583 §D.3d — typed FE API-route client, generated from the route manifest.
 *
 * 583 §D.3a made the Head's HTTP surface machine-inspectable (GET /api/meta/routes). This projects
 * that manifest into a typed TypeScript route table so FE call sites reference a checked constant
 * (`apiPath('GET /api/status')`) instead of a bare string literal — a typo or a removed route becomes
 * a compile error. The generated table is the SINGLE source the FE imports; it is not hand-edited.
 *
 * The manifest is a RUNTIME enumeration of the live Javalin router (there is no static route source
 * to read at build time), so generation is two-step:
 *
 *   1. Capture (needs a running backend, once per route-surface change):
 *        node scripts/codegen/gen-api-client.mjs --from-live=http://127.0.0.1:<apiPort>
 *      → fetches both live Java projections, verifies their identities/count/digest, then writes
 *        route-manifest.snapshot.json, reference-client-openapi.snapshot.json, and the client.
 *   2. Regenerate (offline, from the committed snapshot — this is what CI runs):
 *        node scripts/codegen/gen-api-client.mjs            # write the client
 *        node scripts/codegen/gen-api-client.mjs --check    # exit non-zero on drift
 *
 * Honest scope (the user accepted this as future-proofing, tempdoc 583 §D.7): the committed snapshot
 * is a point-in-time capture and can drift if routes change without a re-capture; the offline --check
 * only guarantees the GENERATED DERIVATIVES match the SNAPSHOT, not that the snapshot matches the
 * live server (CI has no live backend — ADR-0026). Re-run --from-live after changing the route surface.
 */

import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, '..', '..');
// The captured route snapshot is codegen INPUT DATA (not a canonical wire-record schema), so it lives
// next to the generated client — NOT under SSOT/schemas/, which is mirrored into the ui classpath and
// served by SchemaController (a route snapshot is not a schema).
const SNAPSHOT_PATH = join(
  REPO_ROOT,
  'modules',
  'ui-web',
  'src',
  'api',
  'generated',
  'route-manifest.snapshot.json',
);
const OUT_PATH = join(
  REPO_ROOT,
  'modules',
  'ui-web',
  'src',
  'api',
  'generated',
  'apiRoutes.ts',
);
const OPENAPI_SNAPSHOT_PATH = join(
  REPO_ROOT,
  'modules',
  'ui-web',
  'src',
  'api',
  'generated',
  'reference-client-openapi.snapshot.json',
);
const HTTP_METHODS = new Set([
  'delete',
  'get',
  'head',
  'options',
  'patch',
  'post',
  'put',
  'trace',
]);

/** Render the typed client TS from a manifest object ({ schemaVersion, count, routes:[...] }). */
export function renderClient(manifest) {
  const routes = [...(manifest.routes ?? [])].sort((a, b) => {
    const ka = `${a.method} ${a.path}`;
    const kb = `${b.method} ${b.path}`;
    return ka < kb ? -1 : ka > kb ? 1 : 0;
  });
  const seen = new Set();
  const entries = [];
  for (const r of routes) {
    const key = `${r.method} ${r.path}`;
    if (seen.has(key)) continue; // a method+path is unique; guard defensively
    seen.add(key);
    const caps = (r.requiredCapabilities ?? []).map((c) => JSON.stringify(c)).join(', ');
    entries.push(
      `  ${JSON.stringify(key)}: { method: ${JSON.stringify(r.method)}, ` +
        `path: ${JSON.stringify(r.path)}, cohort: ${JSON.stringify(r.cohort)}, ` +
        `requiredCapabilities: [${caps}] },`,
    );
  }
  return `// GENERATED by scripts/codegen/gen-api-client.mjs from modules/ui-web/src/api/generated/route-manifest.snapshot.json
// DO NOT EDIT. Re-capture with: node scripts/codegen/gen-api-client.mjs --from-live=http://127.0.0.1:<apiPort>
// Then regenerate offline with: node scripts/codegen/gen-api-client.mjs
//
// Tempdoc 583 §D.3d — a typed projection of the live route manifest (GET /api/meta/routes). FE call
// sites reference a checked route key instead of a bare string, so a typo/removed route is a compile
// error. The required capability per route comes from the one RouteCapabilityPolicy authority.

export interface ApiRoute {
  readonly method: string;
  readonly path: string;
  readonly cohort: string;
  readonly requiredCapabilities: readonly string[];
}

/** Every route the Head exposes, keyed by "<METHOD> <path>". Snapshot schema v${manifest.schemaVersion ?? '?'}. */
export const API_ROUTES = {
${entries.join('\n')}
} as const satisfies Record<string, ApiRoute>;

export type ApiRouteKey = keyof typeof API_ROUTES;

/** The path template for a route key (compile error on an unknown key). */
export function apiPath(key: ApiRouteKey): string {
  return API_ROUTES[key].path;
}

/** The runtime capabilities a route requires (empty = always available / GET-exempt). */
export function requiredCapabilities(key: ApiRouteKey): readonly string[] {
  return API_ROUTES[key].requiredCapabilities;
}
`;
}

function normalizeOpenApiPath(path) {
  let normalized = path.replaceAll('<', '{').replaceAll('>', '}');
  if (normalized.endsWith('/*')) normalized = `${normalized.slice(0, -1)}{wildcard}`;
  return normalized.replaceAll('*', '{wildcard}');
}

/**
 * Check the two live Java projections before either committed snapshot is replaced.
 * This validates identities; it does not re-render OpenAPI in Node.
 */
export function validateLivePair(manifest, openApi) {
  if (!manifest || !Array.isArray(manifest.routes)) {
    throw new Error('live route manifest returned no routes array');
  }
  if (manifest.count !== manifest.routes.length) {
    throw new Error(`live route manifest count ${manifest.count} != ${manifest.routes.length} routes`);
  }
  const surface = openApi?.['x-justsearch-surface'];
  if (
    surface?.classification !== 'reference-client-structural-inventory' ||
    surface?.runtimeContract !== false
  ) {
    throw new Error('live OpenAPI document is not classified as a non-Runtime-Contract inventory');
  }
  const source = openApi?.['x-justsearch-route-source'];
  if (
    source?.routeCount !== manifest.routes.length ||
    !/^sha256:[0-9a-f]{64}$/.test(manifest.routeDigest ?? '') ||
    source?.routeDigest !== manifest.routeDigest
  ) {
    throw new Error('live route/OpenAPI descriptor count or digest is missing or inconsistent');
  }

  const manifestOperations = new Set(
    manifest.routes.map((route) => `${route.method.toLowerCase()} ${normalizeOpenApiPath(route.path)}`),
  );
  if (manifestOperations.size !== manifest.routes.length) {
    throw new Error('live route manifest contains duplicate method/path identities');
  }
  const openApiOperations = new Set();
  for (const [path, item] of Object.entries(openApi.paths ?? {})) {
    for (const method of Object.keys(item ?? {})) {
      if (HTTP_METHODS.has(method)) openApiOperations.add(`${method} ${path}`);
    }
  }
  const missing = [...manifestOperations].filter((operation) => !openApiOperations.has(operation));
  const extra = [...openApiOperations].filter((operation) => !manifestOperations.has(operation));
  if (missing.length || extra.length) {
    throw new Error(
      `live route/OpenAPI identities differ (missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'})`,
    );
  }
  return Object.freeze({ routeCount: source.routeCount, routeDigest: source.routeDigest });
}

function atomicWriteJson(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.tmp-${process.pid}`;
  try {
    writeFileSync(temporary, JSON.stringify(value, null, 2) + '\n');
    renameSync(temporary, path);
  } finally {
    if (existsSync(temporary)) rmSync(temporary, { force: true });
  }
}

export function canonicalizeJsonMaps(value) {
  if (Array.isArray(value)) return value.map(canonicalizeJsonMaps);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([key, entry]) => [key, canonicalizeJsonMaps(entry)]),
  );
}

async function fetchJson(url) {
  const response = await fetch(url, { headers: { accept: 'application/json' } });
  if (!response.ok) throw new Error(`capture failed: GET ${url} -> HTTP ${response.status}`);
  return response.json();
}

/**
 * Validate the canonical lifecycle gate before enumerating the live route surface.
 * `/api/health` serializes protobuf enum names (LIFECYCLE_STATE_READY, etc.), while
 * the contract names the states by their short values; accept both spellings so this
 * guard remains tied to the canonical state rather than one serializer detail.
 */
export function validateLiveHealth(statusCode, health) {
  if (statusCode !== 200) {
    throw new Error(`live health check failed: GET /api/health -> HTTP ${statusCode}`);
  }
  const rawState = health?.lifecycle?.state;
  const state = typeof rawState === 'string' && rawState.startsWith('LIFECYCLE_STATE_')
    ? rawState.slice('LIFECYCLE_STATE_'.length)
    : rawState;
  if (state !== 'READY' && state !== 'DEGRADED') {
    throw new Error(`live health check failed: lifecycle state ${JSON.stringify(rawState) || '<missing>'}`);
  }
  return Object.freeze({ statusCode, lifecycleState: state });
}

async function fetchLiveHealth(url) {
  const response = await fetch(url, { headers: { accept: 'application/json' } });
  let health;
  try {
    health = await response.json();
  } catch {
    throw new Error(`live health check failed: GET ${url} returned invalid JSON`);
  }
  return validateLiveHealth(response.status, health);
}

export async function captureFromLive(
  baseUrl,
  { routePath = SNAPSHOT_PATH, openApiPath = OPENAPI_SNAPSHOT_PATH } = {},
) {
  const base = baseUrl.replace(/\/$/, '');
  // The route manifest is assembled during startup. `/api/status` can answer before
  // that registration settles, so use the canonical lifecycle gate first and only
  // then capture the two route projections.
  await fetchLiveHealth(`${base}/api/health`);
  const [manifest, openApi] = await Promise.all([
    fetchJson(`${base}/api/meta/routes`),
    fetchJson(`${base}/api/meta/openapi.json`),
  ]);
  const capture = validateLivePair(manifest, openApi);
  atomicWriteJson(routePath, manifest);
  // The offline Java exporter enables ORDER_MAP_ENTRIES_BY_KEYS. Canonicalize the captured
  // wire document the same way so live capture and offline regeneration compare byte-for-byte,
  // independent of Map.of iteration order in the serving JVM.
  atomicWriteJson(openApiPath, canonicalizeJsonMaps(openApi));
  console.log(`captured ${capture.routeCount} routes -> ${routePath}`);
  console.log(`captured matching OpenAPI (${capture.routeDigest}) -> ${openApiPath}`);
  return manifest;
}

function readSnapshot() {
  if (!existsSync(SNAPSHOT_PATH)) {
    throw new Error(
      `no committed snapshot at ${SNAPSHOT_PATH}; run --from-live=<baseUrl> against a running backend first`,
    );
  }
  return JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8'));
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const fromLive = args.find((a) => a.startsWith('--from-live'));

  let manifest;
  if (fromLive) {
    const baseUrl = fromLive.includes('=') ? fromLive.split('=')[1] : args[args.indexOf(fromLive) + 1];
    if (!baseUrl) throw new Error('--from-live requires a base URL, e.g. --from-live=http://127.0.0.1:8080');
    manifest = await captureFromLive(baseUrl);
  } else {
    manifest = readSnapshot();
  }

  const next = renderClient(manifest);
  if (check) {
    const current = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : '';
    if (current !== next) {
      console.error(`DRIFT: ${OUT_PATH} is stale. Run: node scripts/codegen/gen-api-client.mjs`);
      process.exit(1);
    }
    console.log('apiRoutes.ts up to date');
    return;
  }
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, next);
  console.log(`wrote ${OUT_PATH} (${(manifest.routes ?? []).length} routes)`);
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  main().catch((e) => {
    console.error(e.message ?? e);
    process.exit(1);
  });
}
