import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const filename = 'runtime-ready-unavailable-response.v1.json';
const targets = [
  `SSOT/schemas/${filename}`,
  `modules/ui/src/main/resources/SSOT/schemas/${filename}`,
];

export function readinessUnavailableSchema(readiness, apiError) {
  const definition = source => {
    const { $schema, $id, ...body } = source;
    return body;
  };
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `https://ssot.justsearch/v1/schemas/${filename}`,
    $comment: 'Generated by node contracts/runtime/generate-readiness-schema.mjs; do not edit.',
    title: 'JustSearch runtime readiness unavailable response',
    description: 'A readiness probe failure or an Engine admission refusal.',
    oneOf: [
      { $ref: '#/$defs/ReadinessResponse' },
      { $ref: '#/$defs/ApiErrorResponse' },
    ],
    $defs: {
      ReadinessResponse: definition(readiness),
      ApiErrorResponse: definition(apiError),
    },
  };
}

export function generateReadinessSchema(check = false) {
  const read = name => JSON.parse(readFileSync(resolve(root, 'SSOT/schemas', name), 'utf8'));
  const source = JSON.stringify(readinessUnavailableSchema(
    read('runtime-ready-response.v1.json'), read('api-error-response.v1.json'),
  ), null, 2) + '\n';
  for (const target of targets) {
    const path = resolve(root, target);
    if (check) {
      if (readFileSync(path, 'utf8') !== source) throw new Error(`${target} is stale`);
    } else {
      const temporary = `${path}.tmp`;
      writeFileSync(temporary, source, 'utf8');
      renameSync(temporary, path);
    }
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  generateReadinessSchema(process.argv.includes('--check'));
  console.log(`readiness schema: ${process.argv.includes('--check') ? 'current' : 'generated'}`);
}
