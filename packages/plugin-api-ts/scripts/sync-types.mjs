#!/usr/bin/env node
// Fixed, type-only projection of the frozen host contract. Edit canonical files,
// then run sync-types; --check compares without creating or changing any files.
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { replaceDirectory } from './replace-directory.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(pkg, '../..');
const ui = join(repo, 'modules/ui-web/src');
const src = join(pkg, 'src');
const header = '// Generated by scripts/sync-types.mjs from canonical host types. Do not edit.\n';
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: sync-types.mjs [--check]');

function parse(relative) {
  const path = join(ui, relative);
  const text = readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  if (source.parseDiagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(source.parseDiagnostics, diagnosticsHost));
  return source;
}
const diagnosticsHost = { getCanonicalFileName: (f) => f, getCurrentDirectory: () => pkg, getNewLine: () => '\n' };
function declarations(relative, expected) {
  const source = parse(relative);
  return expected.map(([name, kind]) => {
    const matches = source.statements.filter((s) => s.name?.text === name);
    if (matches.length !== 1 || matches[0].kind !== kind || !matches[0].modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) {
      throw new Error(`${relative}: expected exactly one exported ${ts.SyntaxKind[kind]} ${name}`);
    }
    return matches[0].getText(source);
  }).join('\n\n') + '\n';
}
const type = ts.SyntaxKind.TypeAliasDeclaration;
const intf = ts.SyntaxKind.InterfaceDeclaration;
const outputs = new Map();
const plugin = parse('shell-v0/plugin-api/plugin-types.ts');
// Keep the existing public entry contract as well as the new contribution shape.
declarations('shell-v0/plugin-api/plugin-types.ts', [
  ['PluginManifest', intf], ['PluginCapabilities', intf], ['PluginRegisterFn', type],
  ['PluginUnregisterFn', type], ['PluginHostApi', intf], ['PluginSurfaceContribution', intf],
  ['SurfacePortHandler', type], ['SurfacePortContext', intf], ['PluginTrustTier', type],
  ['PluginContribution', intf],
]);
const constants = plugin.statements.filter(ts.isVariableStatement).filter((statement) =>
  statement.declarationList.declarations.some((declaration) => declaration.name.getText(plugin) === 'PLUGIN_CONTRACT_VERSION'));
if (constants.length !== 1 || !(constants[0].declarationList.flags & ts.NodeFlags.Const) ||
    !constants[0].modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
  throw new Error('plugin-types.ts: expected exactly one exported const PLUGIN_CONTRACT_VERSION');
}
// These are the only nonlocal references permitted in the canonical module.
const rewrites = new Map([
  ['../../api/generated/registry-enums.generated.js', './support/enums.js'],
  ['../../api/types/registry.js', './support/registry.js'],
]);
const edits = [];
function visit(node) {
  if (ts.isStringLiteral(node) && rewrites.has(node.text)) {
    edits.push([node.getStart(plugin), node.end, JSON.stringify(rewrites.get(node.text))]);
  }
  ts.forEachChild(node, visit);
}
visit(plugin);
for (const original of rewrites.keys()) {
  if (edits.filter(([start]) => plugin.text.slice(start + 1).startsWith(original)).length !== 1) {
    throw new Error(`plugin-types.ts: expected exactly one reference to ${original}`);
  }
}
let pluginText = plugin.text;
for (const [start, end, replacement] of edits.sort((a, b) => b[0] - a[0])) {
  pluginText = pluginText.slice(0, start) + replacement + pluginText.slice(end);
}
outputs.set('plugin-types.ts', header + pluginText);
outputs.set('trust-types.ts', header + "import type { PluginTrustTier } from './plugin-types.js';\n\n" + declarations('shell-v0/plugin-api/TrustChannel.ts', [['TrustVerdict', intf], ['TrustEvidence', intf], ['TrustChannel', intf]]));
outputs.set('support/enums.ts', header + declarations('api/generated/registry-enums.generated.ts', [['Audience', type], ['TrustTier', type]]));
outputs.set('support/registry.ts', header + "import type { ResourceWire } from './resource.js';\nimport type { PresentationWire } from './presentation.js';\nimport type { ProvenanceWire } from './provenance.js';\n\n" + declarations('api/types/registry.ts', [['Resource', type], ['Presentation', type], ['Provenance', type], ['HistoryPolicy', type], ['Privacy', type], ['ConsumerHook', type], ['OperationRef', type], ['EmissionPolicy', type]]));
for (const [name, expected] of [
  ['resource', [['Audience', type], ['I18nKey', type], ['OperationRef', type], ['OperationRefNullable', type], ['ResourceWire', intf]]],
  ['presentation', [['I18nKey', type], ['PresentationWire', intf]]],
  ['provenance', [['ProvenanceWire', intf]]],
]) outputs.set(`support/${name}.ts`, header + declarations(`api/generated/schema-types/${name}.ts`, expected));

function files(directory, prefix = '') {
  return existsSync(directory) ? readdirSync(directory, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? files(join(directory, entry.name), `${prefix}${entry.name}/`) : [`${prefix}${entry.name}`]).sort() : [];
}
if (process.argv.includes('--check')) {
  const drift = [...outputs].filter(([name, content]) => !existsSync(join(src, name)) || readFileSync(join(src, name), 'utf8').replaceAll('\r\n', '\n') !== content).map(([name]) => name);
  drift.push(...files(src).filter((name) => !outputs.has(name) && readFileSync(join(src, name), 'utf8').replaceAll('\r\n', '\n').startsWith(header)));
  if (drift.length) throw new Error(`SDK types are stale: ${drift.join(', ')}; run npm run sync-types`);
  console.log('SDK types are current');
} else {
  const staged = mkdtempSync(join(pkg, '.sdk-src-'));
  try {
    if (existsSync(src)) cpSync(src, staged, { recursive: true });
    for (const name of files(staged)) {
      if (!outputs.has(name) && readFileSync(join(staged, name), 'utf8').replaceAll('\r\n', '\n').startsWith(header)) rmSync(join(staged, name));
    }
    for (const [name, content] of outputs) {
      mkdirSync(dirname(join(staged, name)), { recursive: true });
      writeFileSync(join(staged, name), content);
    }
    const config = ts.readConfigFile(join(pkg, 'tsconfig.json'), ts.sys.readFile);
    if (config.error) throw new Error(ts.formatDiagnosticsWithColorAndContext([config.error], diagnosticsHost));
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, pkg);
    const program = ts.createProgram(files(staged).filter((f) => f.endsWith('.ts')).map((f) => join(staged, f)), { ...parsed.options, rootDir: staged, noEmit: true, skipLibCheck: false, types: [] });
    const dependencies = program.getSourceFiles().filter((file) => !resolve(file.fileName).startsWith(staged + sep) && !program.isSourceFileDefaultLibrary(file));
    if (dependencies.length) throw new Error(`SDK source depends on files outside its projection: ${dependencies.map((file) => file.fileName).join(', ')}`);
    const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
    if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, diagnosticsHost));
    replaceDirectory(staged, src);
    console.log('SDK types synchronized and typechecked');
  } finally {
    rmSync(staged, { recursive: true, force: true });
  }
}
